/**
 * cookie-exporter.js
 * Cookie export formats and per-domain Netscape export.
 * No UI dependencies.
 */

const HEADER_LINE_1 = '# Netscape HTTP Cookie File';
const HEADER_LINE_2 = '# This file was generated by Zig Zag';

/**
 * Convert a cookie array to Netscape format text.
 * Seven columns: domain, includeSubdomains, path, secure, expiration, name, value
 */
export function toNetscapeFormat(cookies) {
  const lines = [HEADER_LINE_1, HEADER_LINE_2, ''];

  for (const c of cookies) {
    const domain = c.domain;
    const includeSubdomains = c.domainScoped ? 'TRUE' : 'FALSE';
    const path = c.path || '';
    const secure = c.secure ? 'TRUE' : 'FALSE';
    // Session cookies use expiration 0
    const expiration = c.status === 'session' ? '0' : String(Math.floor(c.expirationTimestamp || 0));
    const name = c.name;
    const value = c.value;

    lines.push([domain, includeSubdomains, path, secure, expiration, name, value].join('\t'));
  }

  return lines.join('\n');
}

/**
 * Keep the cookie data the parser supports, without its UI selection flag.
 */
export function toJsonFormat(cookies) {
  const fields = [
    'name', 'value', 'domain', 'path', 'expires', 'expirationTimestamp',
    'size', 'httpOnly', 'secure', 'sameSite', 'status', 'hostOnly',
    'domainScoped', 'remainingLifetime', 'originalLifetime',
  ];
  return JSON.stringify(cookies.map(cookie =>
    Object.fromEntries(fields.map(field => [field, cookie[field]])),
  ), null, 2);
}

/**
 * A Cookie request header has names and values only.
 */
export function toHeaderString(cookies) {
  return cookies.map(cookie => cookie.name + '=' + cookie.value).join('; ');
}

/**
 * Give download and clipboard actions the same format text.
 */
export function buildExportPayload(cookies, format) {
  if (format === 'netscape') {
    return { label: 'Netscape', filename: 'cookies.txt', mimeType: 'text/plain;charset=utf-8', content: toNetscapeFormat(cookies) };
  }
  if (format === 'json') {
    return { label: 'JSON', filename: 'cookies.json', mimeType: 'application/json;charset=utf-8', content: toJsonFormat(cookies) };
  }
  if (format === 'header') {
    return { label: 'Header string', filename: 'cookies-header.txt', mimeType: 'text/plain;charset=utf-8', content: toHeaderString(cookies) };
  }
  throw new Error('Unsupported export format');
}

/**
 * Download a text file with the given content.
 */
export function downloadTextFile(content, filename, mimeType = 'text/plain;charset=utf-8') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Sanitize a domain name for use as a filename.
 */
export function sanitizeFilename(domain) {
  // Remove leading dots, replace invalid chars
  return domain
    .replace(/^\.+/, '')
    .replace(/[^a-zA-Z0-9.-]/g, '_')
    .replace(/\.+/g, '.')
    .replace(/_+/g, '_');
}

/**
 * Apply the shared selection and status rules used by every export target.
 */
export function filterCookiesForExport(cookies, options = {}) {
  const includeExpired = options.includeExpired || false;
  const includeSession = options.includeSession !== false;

  return cookies.filter(c => {
    if (!c.selected) return false;
    if (!includeExpired && c.status === 'expired') return false;
    if (!includeSession && c.status === 'session') return false;
    return true;
  });
}

/**
 * Export all selected cookies as a single cookies.txt file.
 */
export function exportAll(cookies, options = {}) {
  const filtered = filterCookiesForExport(cookies, options);
  if (filtered.length === 0) return 0;
  const content = toNetscapeFormat(filtered);
  downloadTextFile(content, 'cookies.txt');
  return filtered.length;
}

/**
 * Export cookies grouped by domain. Downloads one file per domain.
 */
export function exportByDomain(cookies, options = {}) {
  const filtered = filterCookiesForExport(cookies, options);

  // Group by domain
  const groups = {};
  for (const c of filtered) {
    if (!groups[c.domain]) groups[c.domain] = [];
    groups[c.domain].push(c);
  }

  let totalExported = 0;
  for (const [domain, domainCookies] of Object.entries(groups)) {
    const content = toNetscapeFormat(domainCookies);
    const filename = sanitizeFilename(domain) + '.txt';
    downloadTextFile(content, filename);
    totalExported += domainCookies.length;
  }

  return { domains: Object.keys(groups).length, cookies: totalExported };
}
